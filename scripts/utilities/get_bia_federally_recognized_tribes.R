#' name to its current canonical entry, e.g. "Arctic Village (See Native Village
#' of Venetie Tribal Government)". Those 4 lines resolve to 2 consolidated
#' canonical entries (Native Village of Venetie Tribal Government; Pribilof
#' Islands Aleut Communities of St. Paul & St. George Islands).
#'
#' Encoding note: the printed lines for those 2 consolidated entries are
#' transcribed below but deliberately commented out (575 active rows = 577
#' printed lines − 2). Their printed names carry long parentheticals while
#' `cross_reference_target` uses the short canonical form, so activating them
#' would split each entity into two distinct names downstream. Consequently
#' `filter(!is_cross_reference)` yields 571 rows and OMITS those 2 entities;
#' to recover the full 573 substantive Tribal entities (348 contiguous +
#' 225 Alaska), fold the redirects into their targets, as
#' `build_indigenous_tribe_polygons()` does:
#' `distinct(if_else(is_cross_reference, cross_reference_target, name))`.
#'
#' Tribal names are reproduced verbatim. Per the BIA's own convention, a former,
#' previously listed, or also-known-as ("aka") name appears in parentheses after
#' the current name; these are kept inline within `name`.
#'
#' @return A tibble with one row per published list entry and columns:
#'   \describe{
#'     \item{name}{Character. Tribal entity name, verbatim as published.}
#'     \item{region}{Character. "Contiguous 48 states" or "Alaska" — the BIA
#'       lists Alaska Native entities in a separate section.}
#'     \item{alaska_native}{Logical. `TRUE` for Alaska Native entities
#'       (equivalent to `region == "Alaska"`).}
#'     \item{is_cross_reference}{Logical. `TRUE` for the 4 alphabetical
#'       "(See ...)" redirect lines that are not counted as distinct entities.}
#'     \item{cross_reference_target}{Character. For cross-reference rows, the
#'       canonical entry the line redirects to; `NA` otherwise.}
#'   }
