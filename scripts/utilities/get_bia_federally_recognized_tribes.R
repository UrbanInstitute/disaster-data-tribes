#'   https://www.federalregister.gov/documents/2026/01/30/2026-01899/indian-entities-recognized-by-and-eligible-to-receive-services-from-the-united-states-bureau-of
#'   Accessed 2026-06-04. This is the first list to include the Lumbee Tribe of
#'   North Carolina (added via the FY2026 NDAA, Pub. L. 119-60).
#'
#' Count reconciliation: the BIA notice states 575 recognized Tribal entities,
#' but prints 577 alphabetized list lines. The difference is 4 cross-reference
